#!/usr/bin/env python3
"""Re-runnable check for the G6 follow-up (CG-011, .claude/goals/CG-011-h-deepening-followups/G6-史学考古.md):
the public web pages it relies on say what the record says they say.

- Lurie, DAG I (arXiv math/0608228, HTML full text): the homotopy-level phrase on triangles determined up to a nonunique
  isomorphism, the infinity-level phrase on a contractible space of choices, and "too crude" are present; "functorial"
  occurs exactly once; "Bondal", "Kapranov", "dg-categor" do not occur.
- Bondal-Kapranov, English translation (IOP abstract page): the stated aim is a triangulated category generated by a finite
  number of objects; the abstract does not mention cones or functoriality.

Pages are fetched live; a page that cannot be fetched is reported as SKIP, never as a hit. IOP serves scripted requests a
bot-check page, which is not bypassed, so the Bondal-Kapranov check is normally a SKIP. Only short search keys are kept
here, not the texts. Written 2026-10-21, Claude Code session a15f4b3b. Exit 0 iff every check on a fetched page passes.
"""
import re
import sys
import urllib.request

LURIE = "https://arxiv.org/html/math/0608228"
BK = "https://iopscience.iop.org/article/10.1070/SM1991v070n01ABEH001253"


def fetch(url: str):
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (research quote check)"})
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            html = r.read().decode("utf-8", errors="replace")
    except Exception as e:  # network or HTTP error: report, do not count
        return None, f"{type(e).__name__}: {e}"
    text = re.sub(r"<[^>]+>", " ", html)
    return re.sub(r"\s+", " ", text), None


def main() -> int:
    fails = skips = 0
    lurie, err = fetch(LURIE)
    if lurie is None:
        skips += 1
        print("SKIP lurie", err)
    else:
        body = lurie.split("Generated by")[0]  # drop the HTML-conversion boilerplate at the end
        checks = [
            ("lurie: '(nonunique) isomorphism'", "(nonunique) isomorphism" in body),
            ("lurie: 'contractible space of choices'", "contractible space of choices" in body),
            ("lurie: 'too crude'", "too crude" in body),
            ("lurie: 'functorial' exactly once", len(re.findall(r"functorial", body, re.I)) == 1),
            ("lurie: no Bondal/Kapranov/dg-categor", not re.search(r"Bondal|Kapranov|dg-categor", body)),
        ]
        for name, ok in checks:
            fails += not ok
            print("PASS" if ok else "FAIL", name)
    bk, err = fetch(BK)
    if bk is None:
        skips += 1
        print("SKIP bondal-kapranov", err)
    elif re.search(r"captcha|bot manager", bk, re.I):
        # IOP answers scripted requests with a bot-check page; it is not bypassed. The abstract was read in a browser
        # (G6-史学考古.md records what it says); this check then stays a SKIP.
        skips += 1
        print("SKIP bondal-kapranov: the publisher served a bot-check page (not bypassed); see the G6 record")
    else:
        m = re.search(r"Abstract (.{0,400}?)Export citation", bk)
        if not m:
            skips += 1
            print("SKIP bondal-kapranov: abstract block not found in the fetched page")
        else:
            abstract = m.group(1)
            checks = [
                ("bk: aim is 'generated by a finite number of objects'", "generated by a finite number of objects" in abstract),
                ("bk: abstract mentions neither cone nor functor", not re.search(r"cone|functor", abstract, re.I)),
            ]
            for name, ok in checks:
                fails += not ok
                print("PASS" if ok else "FAIL", name)
    print(f"{fails} FAIL, {skips} SKIP")
    return 0 if fails == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
